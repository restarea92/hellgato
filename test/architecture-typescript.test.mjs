import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { buildTypeScript, SDK_OUTPUTS } from '../scripts/build-typescript.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const config = ts.parseJsonConfigFileContent(ts.readConfigFile(resolve(root, 'tsconfig.sdk.json'), ts.sys.readFile).config, ts.sys, root);
const implementations = config.fileNames.filter(path => /\.(?:ts|mts)$/.test(path) && !/\.d\.(?:ts|mts)$/.test(path));

test('owned SDK implementations are strict TS without any or suppression escape hatches', () => {
  assert.equal(config.options.strict, true);
  assert.equal(config.options.noEmitOnError, true);
  assert.notEqual(config.options.allowJs, true);
  assert.notEqual(config.options.skipLibCheck, true);
  assert.equal(implementations.length, 9);
  for (const path of implementations) {
    const source = readFileSync(path, 'utf8');
    assert.doesNotMatch(source, /@ts-(?:ignore|nocheck|expect-error)/, path);
    const parsed = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);
    function inspect(node) {
      assert.notEqual(node.kind, ts.SyntaxKind.AnyKeyword, `Explicit any in ${path}`);
      ts.forEachChild(node, inspect);
    }
    inspect(parsed);
  }
});

test('strict compiler checks implementation bodies, rather than only public declarations', () => {
  const host = ts.createCompilerHost(config.options);
  const original = host.readFile.bind(host);
  host.readFile = path => {
    const source = original(path);
    return implementations.includes(resolve(path)) && source !== undefined
      ? source + '\nconst strictSourceCanary: number = "must fail source checking";\n'
      : source;
  };
  const program = ts.createProgram(config.fileNames, { ...config.options, noEmit: true }, host);
  const diagnostics = ts.getPreEmitDiagnostics(program);
  for (const path of implementations) {
    assert.ok(diagnostics.some(diagnostic => diagnostic.code === 2322 && resolve(diagnostic.file?.fileName ?? '') === path), `Implementation escaped checking: ${path}`);
  }
});

test('checked compiler output exactly matches the shipped runtime and declaration sources', () => {
  buildTypeScript({ check: true });
  assert.equal(SDK_OUTPUTS.length, 18);
  for (const [, path] of SDK_OUTPUTS) assert.match(readFileSync(resolve(root, path), 'utf8'), /^\/\/ Generated by scripts\/build-typescript\.mjs\./);
});
