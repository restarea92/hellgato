import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, invariant, readJson, json, put } from './release-lib.mjs';
import { releaseChannel, windowsNumericVersion, validatePrereleaseState } from './release-policy.mjs';

export async function syncReleaseMetadata({ root = ROOT, check = false, channel = 'stable' } = {}) {
  const metadata = await readJson(resolve(root, 'packages/windows-release/package.json'));
  invariant(metadata.name === '@hellgato/windows-release' && metadata.private === true && releaseChannel(metadata.version) === channel, 'Windows metadata must contain a private stable version');
  const outputs = new Map([
    ['app/release.json', json({ version: metadata.version, channel })],
    ['installer/version.iss', `; Generated by scripts/sync-release-metadata.mjs. Do not edit.\n#define AppVersion "${metadata.version}"\n#define AppVersionNumeric "${windowsNumericVersion(metadata.version)}"\n`],
  ]);
  for (const [path, content] of outputs) {
    if (check) invariant(await readFile(resolve(root, path), 'utf8').catch(() => null) === content, `Stale generated metadata: ${path}; run pnpm release:metadata`);
    else await put(root, path, content);
  }
  return { version: metadata.version, channel };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  let check = false, planPath, sourceChannel;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check') check = true;
    else if (args[i] === '--source-channel' && args[i + 1] === 'beta') sourceChannel = args[++i];
    else if (args[i] === '--plan' && args[i + 1]) planPath = args[++i];
    else throw new Error('Expected --check and optional --plan .release/plan.json');
  }
  invariant(!planPath || !sourceChannel, 'Source CI metadata cannot use a release plan');
  let channel = 'stable';
  if (sourceChannel) {
    validatePrereleaseState(await readJson(resolve(ROOT, '.changeset/pre.json')));
    channel = releaseChannel((await readJson(resolve(ROOT, 'packages/windows-release/package.json'))).version);
  }
  if (planPath) {
    invariant(resolve(planPath) === resolve(ROOT, '.release/plan.json'), 'Use the checkout release plan');
    const plan = await readJson(resolve(ROOT, planPath));
    invariant([1, 3].includes(plan.schemaVersion) && plan.repository === 'restarea92/hellgato', 'Invalid release metadata plan');
    if (plan.schemaVersion === 3) {
      invariant(plan.candidateOnly === false, 'Public metadata requires release intent');
      channel = releaseChannel((await readJson(resolve(ROOT, 'packages/windows-release/package.json'))).version);
    }
  }
  syncReleaseMetadata({ check, channel }).then(result => console.log(`Windows metadata ${result.version} verified`)).catch(error => { console.error(error.message); process.exitCode = 1; });
}
