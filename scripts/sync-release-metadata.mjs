import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, VERSION, invariant, readJson, json, put } from './release-lib.mjs';

export async function syncReleaseMetadata({ root = ROOT, check = false } = {}) {
  const metadata = await readJson(resolve(root, 'packages/windows-release/package.json'));
  invariant(metadata.name === '@hellgato/windows-release' && metadata.private === true && VERSION.test(metadata.version), 'Windows metadata must contain a private stable version');
  const outputs = new Map([
    ['app/release.json', json({ version: metadata.version, channel: 'stable' })],
    ['installer/version.iss', `; Generated by scripts/sync-release-metadata.mjs. Do not edit.\n#define AppVersion "${metadata.version}"\n`],
  ]);
  for (const [path, content] of outputs) {
    if (check) invariant(await readFile(resolve(root, path), 'utf8').catch(() => null) === content, `Stale generated metadata: ${path}; run pnpm release:metadata`);
    else await put(root, path, content);
  }
  return { version: metadata.version, channel: 'stable' };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  invariant(process.argv.slice(2).every(arg => arg === '--check'), 'Expected only --check');
  syncReleaseMetadata({ check: process.argv.includes('--check') }).then(result => console.log(`Windows metadata ${result.version} verified`)).catch(error => { console.error(error.message); process.exitCode = 1; });
}
